    /**
     * A real PNG: a gradient with a border, so scaling is visible.
     */
    public static function png(int $width = 480, int $height = 280): string
    {
        $image = imagecreatetruecolor($width, $height);

        for ($x = 0; $x < $width; $x++) {
            $colour = imagecolorallocate(
                $image,
                (int) (245 - 120 * ($x / $width)),
                (int) (48 + 120 * ($x / $width)),
                (int) (3 + 90 * ($x / $width)),
            );
            imageline($image, $x, 0, $x, $height, $colour);
        }

        $white = imagecolorallocate($image, 255, 255, 255);
        imagerectangle($image, 8, 8, $width - 9, $height - 9, $white);
        imagestring($image, 5, 20, 20, 'laravel-mailroom', $white);

        ob_start();
        imagepng($image);
        imagedestroy($image);

        return (string) ob_get_clean();
    }

