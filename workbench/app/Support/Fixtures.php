    public static function csv(int $rows = 40): string
    {
        $lines = ['order,customer,item,quantity,total'];

        for ($i = 1; $i <= $rows; $i++) {
            $lines[] = sprintf(
                'A-%04d,%s,"Widget, size %d",%d,%.2f',
                1000 + $i,
                ['Rachel Okonkwo', 'Sam Ihejirika', 'Dara Adeyemi', 'Kit Lindqvist'][$i % 4],
                $i % 5 + 1,
                $i % 3 + 1,
                19.99 * ($i % 3 + 1),
            );
        }

        return implode("\n", $lines)."\n";
    }

