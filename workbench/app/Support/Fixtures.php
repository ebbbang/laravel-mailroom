    protected static function reencode(string $format): string
    {
        $image = imagecreatefromstring(self::png(320, 180));

        ob_start();

        match ($format) {
            'jpeg' => imagejpeg($image, null, 82),
            'gif' => imagegif($image),
            'webp' => imagewebp($image, null, 82),
        };

        imagedestroy($image);

        return (string) ob_get_clean();
    }

